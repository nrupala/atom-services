#!/usr/bin/env node
/**
 * sync-skill — generate the gateway's served-SKILL module from the
 * repo-root SKILL.md (the source of truth), following the
 * sync-rates / sync-docs pattern: the file served at
 * GET /SKILL.md is mechanically the repo file — never a hand-copied
 * page that can drift.
 *
 * Reads <repo-root>/SKILL.md and writes src/skill.generated.ts
 * exporting SKILL_MD (the full markdown) and SKILL_TITLE (its H1).
 * Exits non-zero if SKILL.md is missing or has no H1.
 *
 * Run from rails/gateway/:  node tools/sync-skill.mjs
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const gatewayRoot = join(here, "..");
const repoRoot = join(gatewayRoot, "..", "..");

const p = join(repoRoot, "SKILL.md");
if (!existsSync(p)) {
  console.error("sync-skill: repo-root SKILL.md is missing");
  process.exit(1);
}
const markdown = readFileSync(p, "utf8");
const h1 = /^#\s+(.+)$/m.exec(markdown);
if (!h1) {
  console.error("sync-skill: SKILL.md has no H1 title");
  process.exit(1);
}

const body = `// GENERATED by tools/sync-skill.mjs from the repo-root SKILL.md
// (source of truth). The served GET /SKILL.md body is mechanically
// this file. DO NOT EDIT BY HAND. Re-run: node tools/sync-skill.mjs
// Generated: ${new Date().toISOString()}

export const SKILL_TITLE: string = ${JSON.stringify(h1[1].trim())};

export const SKILL_MD: string = ${JSON.stringify(markdown)};
`;
writeFileSync(join(gatewayRoot, "src", "skill.generated.ts"), body);
console.log(`sync-skill: wrote SKILL module (${markdown.length} chars, title "${h1[1].trim()}")`);
