#!/usr/bin/env node
/**
 * sync-rates — generate the gateway's rate config + catalogue rows
 * from the atoms' contracts (the source of truth for pricing).
 *
 * Reads rails/gateway/atoms.registry.json (which atoms are live),
 * then each atom's contract.yaml `pricing:` block, and writes
 * src/generated.ts. The gateway charges AND displays from that one
 * generated module: displayed == charged, mechanically.
 *
 * Run from rails/gateway/:  node tools/sync-rates.mjs
 * Re-run whenever a contract's pricing block changes (e.g. the owner
 * rules a rate). The contract diff is the audit trail.
 *
 * The contract.yaml files are machine-generated with a stable shape;
 * the pricing block is read with a targeted parser (top-level
 * `pricing:` key, two-space-indented scalar fields). If a contract
 * ever grows a different pricing shape, extend this parser — do not
 * hand-edit src/generated.ts.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const gatewayRoot = join(here, "..");
const repoRoot = join(gatewayRoot, "..", "..");

function parsePricing(contractText, serviceName) {
  const lines = contractText.split("\n");
  const start = lines.findIndex((l) => /^pricing:\s*$/.test(l));
  if (start < 0) throw new Error(`${serviceName}: no pricing: block in contract`);
  const fields = {};
  for (let i = start + 1; i < lines.length; i++) {
    const line = lines[i];
    if (/^\S/.test(line)) break; // next top-level key
    const m = /^  (unit|rate|rate_status):\s*(.+?)\s*$/.exec(line);
    if (m) fields[m[1]] = m[2];
  }
  if (!("unit" in fields) || !("rate" in fields) || !("rate_status" in fields)) {
    throw new Error(`${serviceName}: pricing block missing unit/rate/rate_status`);
  }
  const rateRaw = fields.rate;
  const rate = rateRaw === "null" || rateRaw === "~" ? null : Number(rateRaw);
  if (rate !== null && (!Number.isFinite(rate) || rate < 0)) {
    throw new Error(`${serviceName}: unparseable rate "${rateRaw}"`);
  }
  return { unit: fields.unit, rate, rateStatus: fields.rate_status };
}

const registry = JSON.parse(readFileSync(join(gatewayRoot, "atoms.registry.json"), "utf8"));

const rows = registry.atoms.map((atom) => {
  const contractText = readFileSync(join(repoRoot, atom.contract_path), "utf8");
  const pricing = parsePricing(contractText, atom.service_name);
  return {
    service_name: atom.service_name,
    display_name: atom.display_name,
    description: atom.description,
    category: atom.category,
    deliverable_type: atom.deliverable_type,
    atom_version: atom.atom_version,
    namespace: atom.namespace,
    unit: pricing.unit,
    // Rates are carried in integer micro-USD (1 USD = 1,000,000) so
    // sub-cent rates stay exact. null = unset (owner has not ruled).
    rate_micro: pricing.rate === null ? null : Math.round(pricing.rate * 1_000_000),
    rate_status: pricing.rateStatus,
  };
});

const out = `// GENERATED by tools/sync-rates.mjs from the atoms' contract.yaml
// pricing blocks (source of truth) + atoms.registry.json (live set).
// DO NOT EDIT BY HAND. Re-run: node tools/sync-rates.mjs
// Generated: ${new Date().toISOString()}

export interface AtomRate {
  unit: string;
  /** Integer micro-USD per unit; null = rate unset (owner decision pending). */
  rateMicro: number | null;
  rateStatus: string;
}

export interface CatalogueRow {
  serviceName: string;
  displayName: string;
  description: string;
  category: string;
  deliverableType: string;
  atomVersion: string;
  namespace: string;
  unit: string;
  rateMicro: number | null;
  rateStatus: string;
}

export const RATES: Record<string, AtomRate> = {
${rows.map((r) => `  ${JSON.stringify(r.service_name)}: { unit: ${JSON.stringify(r.unit)}, rateMicro: ${r.rate_micro === null ? "null" : r.rate_micro}, rateStatus: ${JSON.stringify(r.rate_status)} },`).join("\n")}
};

export const CATALOGUE: CatalogueRow[] = [
${rows.map((r) => `  { serviceName: ${JSON.stringify(r.service_name)}, displayName: ${JSON.stringify(r.display_name)}, description: ${JSON.stringify(r.description)}, category: ${JSON.stringify(r.category)}, deliverableType: ${JSON.stringify(r.deliverable_type)}, atomVersion: ${JSON.stringify(r.atom_version)}, namespace: ${JSON.stringify(r.namespace)}, unit: ${JSON.stringify(r.unit)}, rateMicro: ${r.rate_micro === null ? "null" : r.rate_micro}, rateStatus: ${JSON.stringify(r.rate_status)} },`).join("\n")}
];
`;

writeFileSync(join(gatewayRoot, "src", "generated.ts"), out);
console.log(`sync-rates: wrote src/generated.ts with ${rows.length} atom(s): ${rows.map((r) => `${r.service_name} (rate=${r.rate_micro === null ? "null" : r.rate_micro + " micro"}, status=${r.rate_status})`).join(", ")}`);
